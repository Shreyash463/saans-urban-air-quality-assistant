// @vitest-environment jsdom
import '@testing-library/jest-dom/vitest';
import {
  act,
  cleanup,
  fireEvent,
  render,
  screen,
  waitFor,
} from '@testing-library/react';
import axe from 'axe-core';
import { afterEach, beforeEach, describe, expect, it, vi } from 'vitest';
import { Footer } from '../sections/Footer';
import { Hero } from '../sections/Hero';
import { Dashboard, PlanLoadingStatus } from '../sections/Dashboard';
import { ProfileForm } from '../sections/ProfileForm';
import Simulator from '../sections/Simulator';
import Chat from '../sections/Chat';
import { generateMockPlan } from '../services/mockPlanGenerator';
import type { UserProfile } from '../types';

const TEST_PROFILE: UserProfile = {
  city: 'Delhi',
  householdSize: 4,
  hasChildren: true,
  hasElderly: false,
  hasRespiratoryCondition: true,
  commuteMode: 'car',
  commuteKm: 18,
  homeType: 'apartment',
  hasAirPurifier: false,
  cookingFuel: 'lpg',
  budget: 'low',
  language: 'en',
};

async function expectNoA11yViolations(container: HTMLElement) {
  const results = await axe.run(container, {
    rules: {
      // Components render in isolation without full <main> landmark wrapper in unit tests
      region: { enabled: false },
    },
  });
  expect(results.violations).toEqual([]);
}

describe('Dashboard loading stages, export actions, and axe accessibility across main sections', () => {
  beforeEach(() => {
    vi.stubEnv('VITE_USE_MOCK', 'true');
  });

  afterEach(() => {
    cleanup();
    vi.unstubAllEnvs();
    vi.restoreAllMocks();
  });

  it('renders loading stages with aria-live status and cold-start hint after 6s', () => {
    vi.useFakeTimers();
    try {
      render(<PlanLoadingStatus language="en" />);
      const status = screen.getByRole('status');
      expect(status).toHaveAttribute('aria-live', 'polite');
      expect(screen.getAllByText('Checking live air quality').length).toBeGreaterThan(
        0
      );
      expect(screen.getByText('Personalizing with Gemini')).toBeInTheDocument();
      expect(screen.getByText('Running safety checks')).toBeInTheDocument();
      expect(screen.queryByText(/waking up the server/i)).not.toBeInTheDocument();

      act(() => {
        vi.advanceTimersByTime(6100);
      });
      expect(screen.getByText(/waking up the server/i)).toBeInTheDocument();
    } finally {
      vi.useRealTimers();
    }
  });

  it('shows Gemini/fallback badges, handles copy/download/print safely, and passes axe', async () => {
    const geminiPlan = {
      ...generateMockPlan(TEST_PROFILE),
      generatedBy: 'gemini' as const,
      aqi: {
        city: 'Delhi',
        aqi: 320,
        dominantPollutant: 'PM2.5',
        updatedAt: '2026-11-25T06:30:00Z',
        source: 'live' as const,
        sourceDetail: 'Open-Meteo, PM-based CPCB estimate',
      },
    };

    const writeText = vi.fn().mockResolvedValue(undefined);
    Object.defineProperty(navigator, 'clipboard', {
      configurable: true,
      value: { writeText },
    });
    const printSpy = vi.spyOn(window, 'print').mockImplementation(() => {
      throw new Error('Blocked in sandbox');
    });

    const { container } = render(
      <Dashboard
        plan={geminiPlan}
        language="en"
        announcement="Your personalized clean-air plan is ready."
        isLoading={false}
      />
    );

    expect(screen.getByTestId('plan-generator-badge')).toHaveTextContent(
      'Generated by Gemini'
    );
    expect(
      screen.getByText('Live · updated 12:00 IST (Open-Meteo)')
    ).toBeInTheDocument();

    fireEvent.click(screen.getByRole('button', { name: 'Copy plan' }));
    await waitFor(() => {
      expect(writeText).toHaveBeenCalledTimes(1);
    });
    expect(screen.getByText('Clean-air plan copied to clipboard.')).toBeInTheDocument();

    fireEvent.click(screen.getByRole('button', { name: 'Print / Save plan' }));
    expect(printSpy).toHaveBeenCalled();
    expect(
      screen.getByText(/Print dialog is unavailable in this window/i)
    ).toBeInTheDocument();

    await expectNoA11yViolations(container);
  });

  it('passes automated axe checks on Hero, ProfileForm, Simulator, Chat, and Footer', async () => {
    const plan = generateMockPlan(TEST_PROFILE);

    const heroRender = render(
      <Hero
        language="en"
        previewReading={plan.aqi}
        reducedMotion={true}
        isDark={false}
      />
    );
    await expectNoA11yViolations(heroRender.container);
    cleanup();

    const profileRender = render(
      <ProfileForm
        profile={TEST_PROFILE}
        onChangeProfile={vi.fn()}
        onSubmitProfile={vi.fn()}
        onClearData={vi.fn()}
        isSubmitting={false}
      />
    );
    await expectNoA11yViolations(profileRender.container);
    cleanup();

    const simRender = render(<Simulator profile={TEST_PROFILE} />);
    await expectNoA11yViolations(simRender.container);
    cleanup();

    const chatRender = render(<Chat profile={TEST_PROFILE} plan={plan} />);
    await expectNoA11yViolations(chatRender.container);
    cleanup();

    const footerRender = render(
      <Footer language="en" reducedMotion={true} onToggleReducedMotion={vi.fn()} />
    );
    await expectNoA11yViolations(footerRender.container);
  });
});
