"""Generates committed OpenAPI, JSON Schema, and TypeScript contract definitions from Pydantic."""

from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path
from typing import Any

BACKEND_DIR = Path(__file__).resolve().parents[1]
REPO_ROOT = BACKEND_DIR.parent
if str(BACKEND_DIR) not in sys.path:
    sys.path.insert(0, str(BACKEND_DIR))

from app.main import create_app  # noqa: E402
from app.schemas import (  # noqa: E402
    AirQualityReading,
    Alternative,
    ChatReply,
    ChatRequest,
    CommunityAction,
    CoordinatesBody,
    HealthResponse,
    IndoorHack,
    PlanRequest,
    PlanResponse,
    RoutineItem,
    UserProfile,
)

_MODELS = (
    UserProfile,
    CoordinatesBody,
    PlanRequest,
    AirQualityReading,
    RoutineItem,
    IndoorHack,
    Alternative,
    CommunityAction,
    PlanResponse,
    ChatRequest,
    ChatReply,
    HealthResponse,
)

_ALIASES_TS = """export type CommuteMode =
  | 'car'
  | 'two_wheeler'
  | 'public_transport'
  | 'walk_cycle'
  | 'work_from_home';

export type HomeType = 'apartment' | 'independent_house';

export type CookingFuel =
  | 'lpg'
  | 'induction_electric'
  | 'piped_gas'
  | 'biomass_wood';

export type BudgetLevel = 'low' | 'medium' | 'high';
export type LanguageCode = 'en' | 'hi';
export type FallbackReason = 'no_key' | 'ai_busy' | 'ai_error';
export type CommunityActor = 'rwa' | 'school' | 'workplace' | 'neighbours';
export type EffortLevel = 'low' | 'medium' | 'high';
export type RoutineTimeSlot = 'morning' | 'midday' | 'evening' | 'night';
export type CostLevel = 'free' | 'low' | 'medium' | 'high';
export type ReadingSource = 'live' | 'demo';
export type GeneratedBy = 'gemini' | 'rules';
"""


def _resolve_ref(ref: str) -> str:
    return ref.rsplit("/", 1)[-1]


_PRIMITIVE_TS_TYPES: dict[str, str] = {
    "null": "null",
    "string": "string",
    "integer": "number",
    "number": "number",
    "boolean": "boolean",
}


def _schema_to_ts(prop: dict[str, Any], defs: dict[str, Any], known_enum_map: dict[str, str]) -> str:
    if "$ref" in prop:
        return _resolve_ref(prop["$ref"])
    if "anyOf" in prop:
        return " | ".join(dict.fromkeys(_schema_to_ts(opt, defs, known_enum_map) for opt in prop["anyOf"]))
    if "enum" in prop:
        vals = tuple(prop["enum"])
        return known_enum_map.get(vals) or " | ".join(json.dumps(v) for v in vals)
    if "const" in prop:
        return json.dumps(prop["const"])
    typ = prop.get("type")
    if isinstance(typ, str) and typ in _PRIMITIVE_TS_TYPES:
        return _PRIMITIVE_TS_TYPES[typ]
    if typ == "array":
        item_ts = _schema_to_ts(prop.get("items", {}), defs, known_enum_map)
        return f"({item_ts})[]" if " | " in item_ts else f"{item_ts}[]"
    return "unknown"


def _build_contract_schema() -> dict[str, Any]:
    defs: dict[str, Any] = {}
    for model in _MODELS:
        schema = model.model_json_schema(by_alias=True)
        for sub_name, sub_def in schema.pop("$defs", {}).items():
            defs[sub_name] = sub_def
        defs[model.__name__] = schema
    return {
        "$schema": "https://json-schema.org/draft/2020-12/schema",
        "title": "SaansApiContract",
        "models": dict(sorted(defs.items())),
    }


def _render_ts(contract_schema: dict[str, Any]) -> str:
    enum_map: dict[tuple[Any, ...], str] = {
        ("car", "two_wheeler", "public_transport", "walk_cycle", "work_from_home"): "CommuteMode",
        ("apartment", "independent_house"): "HomeType",
        ("lpg", "induction_electric", "piped_gas", "biomass_wood"): "CookingFuel",
        ("low", "medium", "high"): "BudgetLevel",
        ("en", "hi"): "LanguageCode",
        ("no_key", "ai_busy", "ai_error"): "FallbackReason",
        ("rwa", "school", "workplace", "neighbours"): "CommunityActor",
        ("morning", "midday", "evening", "night"): "RoutineTimeSlot",
        ("free", "low", "medium", "high"): "CostLevel",
        ("live", "demo"): "ReadingSource",
        ("gemini", "rules"): "GeneratedBy",
    }
    models: dict[str, Any] = contract_schema["models"]
    lines = [
        "// AUTO-GENERATED BY backend/scripts/export_contract.py — DO NOT EDIT MANUALLY.",
        "",
        _ALIASES_TS.rstrip(),
        "",
    ]
    for model in _MODELS:
        name = model.__name__
        schema = models[name]
        props: dict[str, Any] = schema.get("properties", {})
        required = set(schema.get("required", []))
        lines.append(f"export interface {name} {{")
        for field_name, prop in props.items():
            opt = "" if field_name in required else "?"
            ts_type = _schema_to_ts(prop, models, enum_map)
            if name == "CommunityAction" and field_name == "effort":
                ts_type = "EffortLevel"
            lines.append(f"  {field_name}{opt}: {ts_type};")
        lines.append("}")
        lines.append("")
    return "\n".join(lines)


def _render_openapi() -> str:
    app = create_app()
    spec = app.openapi()
    return json.dumps(spec, indent=2, sort_keys=True) + "\n"


def main() -> int:
    parser = argparse.ArgumentParser(description="Export OpenAPI, JSON Schema, and TypeScript contract.")
    parser.add_argument("--check", action="store_true", help="Fail if generated files differ from disk.")
    args = parser.parse_args()

    contract_schema = _build_contract_schema()
    schema_text = json.dumps(contract_schema, indent=2, sort_keys=True) + "\n"
    ts_text = _render_ts(contract_schema)
    openapi_text = _render_openapi()

    targets = {
        REPO_ROOT / "contract" / "api.schema.json": schema_text,
        REPO_ROOT / "frontend" / "src" / "types" / "generated.ts": ts_text,
        REPO_ROOT / "docs" / "openapi.json": openapi_text,
    }

    stale: list[Path] = []
    for path, content in targets.items():
        current = path.read_text(encoding="utf-8") if path.exists() else None
        if args.check:
            if current != content:
                stale.append(path)
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            if current != content:
                path.write_text(content, encoding="utf-8", newline="\n")
                print(f"wrote {path.relative_to(REPO_ROOT)}")

    if args.check and stale:
        for p in stale:
            print(f"STALE: {p.relative_to(REPO_ROOT)}", file=sys.stderr)
        return 1
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
